#!/usr/bin/env python3
"""Convert lib/l10n ARB files into Android string resources for android-native.

Writes `values[-<locale>]/strings_arb.xml` and `xml/locales_config.xml`.
ICU plurals become one string per exact branch (`<name>_eq<N>`) plus
`<name>_other`, which keeps ICU's exact-match semantics that Android
`<plurals>` cannot express.

    python3 scripts/arb_to_android.py           # regenerate
    python3 scripts/arb_to_android.py --check   # fail if resources are stale
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from icu_arb import parse_plural_message  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
ARB_DIR = REPO / "lib" / "l10n"
RES_DIR = REPO / "android-native" / "app" / "src" / "main" / "res"
OUTPUT_NAME = "strings_arb.xml"
HEADER = "<!-- GENERATED by scripts/arb_to_android.py from lib/l10n/*.arb. Do not edit. -->"

_PLACEHOLDER = re.compile(r"\{(\w+)\}")
_ICU_HEAD = re.compile(r"^\{(\w+),\s*(\w+),")
_EXACT = re.compile(r"^=(\d+)$")
_ENTITY = re.compile(r"&#(\d+);")


class ConversionError(Exception):
    pass


def resource_name(key: str) -> str:
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", key)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return name.lower()


def qualifier(locale: str, default: str) -> str:
    if locale == default:
        return "values"
    parts = locale.replace("-", "_").split("_")
    if len(parts) == 1:
        return f"values-{parts[0]}"
    if len(parts) == 2 and len(parts[1]) == 2 and parts[1].isupper():
        return f"values-{parts[0]}-r{parts[1]}"
    return "values-b+" + "+".join(parts)


def android_escape(text: str) -> str:
    out = (
        text.replace("\\", "\\\\")
        .replace("'", "\\'")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
        .replace("&", "&amp;")
        .replace("<", "&lt;")
    )
    if out.startswith(("@", "?")):
        out = "\\" + out
    if out.startswith(" "):
        out = "\\u0020" + out[1:]
    if out.endswith(" "):
        out = out[:-1] + "\\u0020"
    return out


def _format(text: str, placeholders: list[tuple[str, str]], with_args: bool) -> str:
    index = {name: (i + 1, kind) for i, (name, kind) in enumerate(placeholders)}
    if with_args:
        text = text.replace("%", "%%")

    def arg(match: re.Match[str]) -> str:
        name = match.group(1)
        if name not in index:
            raise ConversionError(f"unknown placeholder {{{name}}}")
        position, kind = index[name]
        return f"%{position}${'d' if kind == 'int' else 's'}"

    text = _PLACEHOLDER.sub(arg, text)
    if "{" in text or "}" in text:
        raise ConversionError(f"unsupported ICU syntax in: {text[:60]}")
    return text


def convert_message(message: str, placeholders: list[tuple[str, str]]):
    """Returns ("string", text) or ("plural", {"eq<N>": text, ..., "other": text})."""
    message = _ENTITY.sub(lambda m: chr(int(m.group(1))), message)
    head = _ICU_HEAD.match(message)
    if head:
        if head.group(2) != "plural":
            raise ConversionError(f"unsupported ICU {head.group(2)}: {message[:60]}")
        try:
            _, branches = parse_plural_message(message)
        except ValueError as error:
            raise ConversionError(str(error)) from error
        result: dict[str, str] = {}
        for selector, text in branches:
            exact = _EXACT.match(selector)
            if exact:
                key = f"eq{exact.group(1)}"
            elif selector == "other":
                key = "other"
            else:
                raise ConversionError(f"plural keyword '{selector}' is not supported; use =N branches and other")
            result[key] = _format(text, placeholders, with_args=True)
        if "other" not in result:
            raise ConversionError(f"plural without other: {message[:60]}")
        return "plural", result
    used = bool(_PLACEHOLDER.search(message))
    return "string", _format(message, placeholders, with_args=used)


def _placeholders(template: dict, key: str) -> list[tuple[str, str]]:
    meta = template.get(f"@{key}", {}).get("placeholders")
    if meta:
        return [(name, spec.get("type", "Object")) for name, spec in meta.items()]
    seen: list[tuple[str, str]] = []
    for name in _PLACEHOLDER.findall(template[key]):
        if name not in (n for n, _ in seen):
            seen.append((name, "Object"))
    return seen


def _load(arb_dir: Path) -> dict[str, dict]:
    arbs = {}
    for path in sorted(arb_dir.glob("app_*.arb")):
        data = json.loads(path.read_text(encoding="utf-8"))
        arbs[data.get("@@locale", path.stem.removeprefix("app_"))] = data
    return arbs


def _resources(entries: list[str]) -> str:
    body = "\n".join(entries)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"{HEADER}\n"
        '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="MissingTranslation,UnusedResources">\n'
        f"{body}\n"
        "</resources>\n"
    )


def generate(arb_dir: Path, res_dir: Path, template: str) -> dict[Path, str]:
    arbs = _load(arb_dir)
    if template not in arbs:
        raise ConversionError(f"template app_{template}.arb not found in {arb_dir}")
    base = arbs[template]
    keys = [k for k in base if not k.startswith("@")]
    specs = {key: _placeholders(base, key) for key in keys}
    template_plurals = {}
    files: dict[Path, str] = {}
    for locale in [template] + sorted(l for l in arbs if l != template):
        data = arbs[locale]
        entries: list[str] = []
        for key in keys:
            if key not in data:
                continue
            try:
                kind, value = convert_message(data[key], specs[key])
            except ConversionError as error:
                raise ConversionError(f"{locale}/{key}: {error}") from error
            name = resource_name(key)
            if kind == "string":
                entries.append(f'    <string name="{name}">{android_escape(value)}</string>')
                continue
            if locale == template:
                template_plurals[key] = value
            branches = {b: value.get(b, value["other"]) for b in template_plurals.get(key, value)}
            for branch in sorted(branches, key=lambda b: (b == "other", b)):
                entries.append(f'    <string name="{name}_{branch}">{android_escape(branches[branch])}</string>')
        files[res_dir / qualifier(locale, template) / OUTPUT_NAME] = _resources(entries)
    locales = "\n".join(f'  <locale android:name="{l.replace("_", "-")}"/>' for l in [template] + sorted(l for l in arbs if l != template))
    files[res_dir / "xml" / "locales_config.xml"] = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"{HEADER}\n"
        '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n'
        f"{locales}\n"
        "</locale-config>\n"
    )
    return files


def _template_locale() -> str:
    config = REPO / "l10n.yaml"
    match = re.search(r"template-arb-file:\s*app_(\w+)\.arb", config.read_text(encoding="utf-8")) if config.exists() else None
    return match.group(1) if match else "en"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when generated resources are out of date")
    args = parser.parse_args(argv)
    try:
        files = generate(ARB_DIR, RES_DIR, _template_locale())
    except ConversionError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    stale = [p for p in RES_DIR.glob(f"values*/{OUTPUT_NAME}") if p not in files]
    changed = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for path in changed + stale:
            print(f"out of date: {path.relative_to(REPO)}", file=sys.stderr)
        if changed or stale:
            print("run: python3 scripts/arb_to_android.py", file=sys.stderr)
            return 1
        return 0
    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[path], encoding="utf-8")
    for path in stale:
        path.unlink()
    print(f"{len(changed)} written, {len(stale)} removed, {len(files) - len(changed)} unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
